"""Aggregate three LLM classifications of public medical QA benchmarks.

The input result files are generated by ``openbenchmark_process.py``. This
script reproduces the LLM agreement, majority-vote filtering, and benchmark
composition statistics; it does not include the private human evaluation.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

BENCHMARK_BY_SOURCE = {
    "openlifescienceai/medmcqa": "MedMCQA",
    "openlifescienceai/medqa": "MedQA",
    "openlifescienceai/mmlu_clinical_knowledge": "MMLU",
    "openlifescienceai/mmlu_professional_medicine": "MMLU",
    "TsinghuaC3I/MedXpertQA": "MedXpertQA",
    "medbullets_op5": "MedBullets",
}
BENCHMARK_ORDER = list(dict.fromkeys(BENCHMARK_BY_SOURCE.values()))

QUESTION_TYPES = {"DIAGNOSIS", "MANAGEMENT", "BASIC_SCIENCE", "OTHER"}
TARGET_POPULATIONS = {"Pediatric", "Adult", "General"}
REQUIRED_COLUMNS = {
    "id",
    "source",
    "question_type",
    "target_population",
    "is_anesthesia_model",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Compute three-model agreement and majority-vote statistics."
    )
    parser.add_argument("--gemma-results", type=Path, required=True)
    parser.add_argument("--medgemma-results", type=Path, required=True)
    parser.add_argument("--llama-results", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument(
        "--expected-total-before",
        type=int,
        default=10_718,
        help="Expected number of unique items before disagreement filtering.",
    )
    parser.add_argument(
        "--expected-total-after",
        type=int,
        default=10_636,
        help="Expected number of items after disagreement filtering.",
    )
    parser.add_argument(
        "--validate-paper-counts",
        action="store_true",
        help="Fail unless the four headline majority-vote counts match the paper.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Allow overwriting files in the output directory.",
    )
    return parser.parse_args()


def load_model_results(path: Path, model_name: str) -> pd.DataFrame:
    if not path.is_file():
        raise FileNotFoundError(f"{model_name} result file not found: {path}")

    df = pd.read_pickle(path)
    missing = sorted(REQUIRED_COLUMNS - set(df.columns))
    if missing:
        raise ValueError(f"{model_name} results are missing columns: {missing}")

    result = df[list(REQUIRED_COLUMNS)].copy()
    if result["id"].isna().any():
        raise ValueError(f"{model_name} results contain missing IDs.")
    if result["id"].duplicated().any():
        duplicates = result.loc[result["id"].duplicated(), "id"].head().tolist()
        raise ValueError(
            f"{model_name} results contain duplicate IDs: {duplicates}"
        )
    if result[list(REQUIRED_COLUMNS - {"id", "source"})].isna().any().any():
        raise ValueError(f"{model_name} results contain missing classifications.")

    invalid_question_types = set(result["question_type"]) - QUESTION_TYPES
    if invalid_question_types:
        raise ValueError(
            f"{model_name} has invalid question types: "
            f"{sorted(invalid_question_types)}"
        )
    invalid_populations = set(result["target_population"]) - TARGET_POPULATIONS
    if invalid_populations:
        raise ValueError(
            f"{model_name} has invalid target populations: "
            f"{sorted(invalid_populations)}"
        )
    if not result["is_anesthesia_model"].map(
        lambda value: isinstance(value, (bool, np.bool_))
    ).all():
        raise ValueError(f"{model_name} has non-boolean anesthesia labels.")

    result["is_anesthesia_model"] = result["is_anesthesia_model"].astype(bool)
    result["model"] = model_name
    return result


def validate_model_alignment(model_frames: list[pd.DataFrame]) -> None:
    reference = model_frames[0].set_index("id")["source"].sort_index()
    for frame in model_frames[1:]:
        candidate = frame.set_index("id")["source"].sort_index()
        if not reference.index.equals(candidate.index):
            missing = reference.index.difference(candidate.index).tolist()[:5]
            extra = candidate.index.difference(reference.index).tolist()[:5]
            raise ValueError(
                "Model result files do not contain identical IDs. "
                f"Missing examples: {missing}; extra examples: {extra}"
            )
        if not reference.equals(candidate):
            raise ValueError("Dataset source differs between models for at least one ID.")


def make_fleiss_matrix(
    df: pd.DataFrame,
    item_col: str,
    rater_col: str,
    label_col: str,
) -> tuple[np.ndarray, list[Any]]:
    duplicated = df.duplicated([item_col, rater_col])
    if duplicated.any():
        examples = df.loc[duplicated, [item_col, rater_col]].head().to_dict("records")
        raise ValueError(f"Duplicate item-rater classifications: {examples}")

    n_raters = df[rater_col].nunique()
    label_counts = pd.crosstab(df[item_col], df[label_col])
    if not (label_counts.sum(axis=1) == n_raters).all():
        raise ValueError(
            f"Every item must have exactly {n_raters} non-null ratings for {label_col}."
        )

    labels = sorted(label_counts.columns.tolist(), key=str)
    matrix = label_counts.reindex(columns=labels, fill_value=0).to_numpy(dtype=int)
    return matrix, labels


def compute_fleiss_for_column(
    df: pd.DataFrame,
    item_col: str,
    rater_col: str,
    label_col: str,
) -> dict[str, Any]:
    try:
        from statsmodels.stats.inter_rater import fleiss_kappa
    except ImportError as exc:
        raise ImportError(
            "Fleiss kappa requires statsmodels. Install the project dependencies "
            "before running the analysis."
        ) from exc

    matrix, labels = make_fleiss_matrix(df, item_col, rater_col, label_col)
    return {
        "column": label_col,
        "kappa": float(fleiss_kappa(matrix)),
        "labels": labels,
        "n_items": int(matrix.shape[0]),
    }


def majority_vote(labels: list[Any]) -> Any:
    if len(labels) != 3 or any(pd.isna(label) for label in labels):
        raise ValueError(f"Expected three valid labels, received: {labels}")
    counts = Counter(labels)
    label, count = counts.most_common(1)[0]
    return label if count >= 2 else None


def all_different(labels: list[Any]) -> bool:
    if len(labels) != 3 or any(pd.isna(label) for label in labels):
        raise ValueError(f"Expected three valid labels, received: {labels}")
    return len(set(labels)) == 3


def aggregate_majority_vote(total: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    grouped = total.groupby(["id", "source"], as_index=False).agg(
        target_population_list=("target_population", list),
        question_type_list=("question_type", list),
        is_anesthesia_list=("is_anesthesia_model", list),
        n_ratings=("model", "size"),
    )
    if not (grouped["n_ratings"] == 3).all():
        raise ValueError("Every item must have exactly three model ratings.")

    grouped["target_population_all_different"] = grouped[
        "target_population_list"
    ].apply(all_different)
    grouped["question_type_all_different"] = grouped[
        "question_type_list"
    ].apply(all_different)
    exclusion_mask = (
        grouped["target_population_all_different"]
        | grouped["question_type_all_different"]
    )

    excluded = grouped.loc[
        exclusion_mask,
        [
            "id",
            "source",
            "target_population_list",
            "question_type_list",
            "target_population_all_different",
            "question_type_all_different",
        ],
    ].copy()

    retained = grouped.loc[~exclusion_mask].copy()
    retained["target_population"] = retained["target_population_list"].apply(
        majority_vote
    )
    retained["question_type"] = retained["question_type_list"].apply(majority_vote)
    retained["is_anesthesia"] = retained["is_anesthesia_list"].apply(majority_vote)

    majority_df = retained[
        ["id", "source", "target_population", "question_type", "is_anesthesia"]
    ].copy()
    if majority_df[
        ["target_population", "question_type", "is_anesthesia"]
    ].isna().any().any():
        raise RuntimeError("A retained item does not have a valid majority label.")
    majority_df["is_anesthesia"] = majority_df["is_anesthesia"].astype(bool)
    return majority_df, excluded


def summarize_group(rows: pd.DataFrame) -> dict[str, Any]:
    total = len(rows)
    diagnosis_or_basic = rows["question_type"].isin(
        ["DIAGNOSIS", "BASIC_SCIENCE"]
    )
    pediatric = rows["target_population"].eq("Pediatric")
    anesthesia = rows["is_anesthesia"]
    pediatric_anesthesia = pediatric & anesthesia

    def metric(mask: pd.Series) -> dict[str, float | int]:
        count = int(mask.sum())
        return {
            "count": count,
            "percentage": 100.0 * count / total if total else float("nan"),
        }

    return {
        "total": total,
        "diagnosis_or_basic_science": metric(diagnosis_or_basic),
        "pediatric": metric(pediatric),
        "anesthesia": metric(anesthesia),
        "pediatric_anesthesia": metric(pediatric_anesthesia),
    }


def print_summary(label: str, summary: dict[str, Any]) -> None:
    print(f"\nDataset: {label}")
    print(f"Total: {summary['total']:,}")
    for key, display_name in (
        ("diagnosis_or_basic_science", "Diagnosis or basic science"),
        ("pediatric", "Pediatric"),
        ("anesthesia", "Anesthesiology"),
        ("pediatric_anesthesia", "Pediatric anesthesiology"),
    ):
        value = summary[key]
        print(
            f"{display_name}: {value['count']:,}/{summary['total']:,} "
            f"({value['percentage']:.5f}%)"
        )


def ensure_writable_outputs(paths: list[Path], overwrite: bool) -> None:
    existing = [path for path in paths if path.exists()]
    if existing and not overwrite:
        raise FileExistsError(
            "Output already exists. Use --overwrite to replace it: "
            + ", ".join(str(path) for path in existing)
        )


def main() -> None:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    output_paths = {
        "majority_pickle": args.output_dir / "openbench_llm_majority_vote.pkl",
        "excluded_csv": args.output_dir / "openbench_excluded_items.csv",
        "summary_json": args.output_dir / "openbench_summary.json",
    }
    ensure_writable_outputs(list(output_paths.values()), args.overwrite)

    model_frames = [
        load_model_results(args.gemma_results, "gemma"),
        load_model_results(args.medgemma_results, "medgemma"),
        load_model_results(args.llama_results, "llama"),
    ]
    validate_model_alignment(model_frames)

    n_items_before = len(model_frames[0])
    if args.expected_total_before and n_items_before != args.expected_total_before:
        raise ValueError(
            f"Expected {args.expected_total_before:,} items before filtering, "
            f"found {n_items_before:,}."
        )

    total = pd.concat(model_frames, ignore_index=True)
    agreement = [
        compute_fleiss_for_column(total, "id", "model", column)
        for column in (
            "target_population",
            "question_type",
            "is_anesthesia_model",
        )
    ]
    print("Inter-model Fleiss kappa:")
    for result in agreement:
        print(
            f"- {result['column']}: {result['kappa']:.4f} "
            f"(n={result['n_items']:,}, labels={result['labels']})"
        )

    majority_df, excluded = aggregate_majority_vote(total)
    if args.expected_total_after and len(majority_df) != args.expected_total_after:
        raise ValueError(
            f"Expected {args.expected_total_after:,} retained items, "
            f"found {len(majority_df):,}; excluded {len(excluded):,}."
        )

    majority_df["benchmark"] = majority_df["source"].map(BENCHMARK_BY_SOURCE)
    if majority_df["benchmark"].isna().any():
        unmapped = sorted(
            majority_df.loc[majority_df["benchmark"].isna(), "source"].unique()
        )
        raise ValueError(f"Sources missing from BENCHMARK_BY_SOURCE: {unmapped}")

    summaries: dict[str, Any] = {"overall": summarize_group(majority_df)}
    for benchmark, rows in majority_df.groupby("benchmark", sort=False):
        summaries[benchmark] = summarize_group(rows)

    print_summary("Overall", summaries["overall"])
    for benchmark in BENCHMARK_ORDER:
        print_summary(benchmark, summaries[benchmark])

    expected_paper_counts = {
        "diagnosis_or_basic_science": 8_480,
        "pediatric": 1_268,
        "anesthesia": 321,
        "pediatric_anesthesia": 17,
    }
    observed_paper_counts = {
        key: int(summaries["overall"][key]["count"])
        for key in expected_paper_counts
    }
    if args.validate_paper_counts and observed_paper_counts != expected_paper_counts:
        raise ValueError(
            "Headline counts do not match the paper. "
            f"Expected {expected_paper_counts}, observed {observed_paper_counts}."
        )

    output_summary = {
        "n_items_before_filtering": n_items_before,
        "n_excluded": len(excluded),
        "n_items_after_filtering": len(majority_df),
        "agreement": agreement,
        "paper_headline_counts_expected": expected_paper_counts,
        "paper_headline_counts_observed": observed_paper_counts,
        "dataset_summaries": summaries,
    }

    majority_df.to_pickle(output_paths["majority_pickle"])
    excluded.assign(
        target_population_list=excluded["target_population_list"].apply(json.dumps),
        question_type_list=excluded["question_type_list"].apply(json.dumps),
    ).to_csv(output_paths["excluded_csv"], index=False)
    with output_paths["summary_json"].open("w", encoding="utf-8") as file:
        json.dump(output_summary, file, ensure_ascii=False, indent=2)

    print("\nSaved outputs:")
    for path in output_paths.values():
        print(f"- {path}")


if __name__ == "__main__":
    main()
